"""Generate slides_numbers.tex from machine-readable results."""
from pathlib import Path
import json
R=Path(__file__).resolve().parent
c=json.loads((R/'core/results.json').read_text())
r=json.loads((R/'robustness/results.json').read_text())
s=json.loads((R/'sparsity/results.json').read_text())
t=c['test']; seed=c['seed_summaries']

lines=[]
def cmd(name,value):
    lines.append(rf'\newcommand{{\{name}}}{{{value}}}')

for name,key in [('Rand','random'),('Disc','disjoint'),('Hyb','hybrid'),('Ctx','contextual_greedy'),
                 ('Eps','epsilon_greedy'),('Win','window'),('Log','logistic')]:
    z=t[key]
    cmd(name+'M',z['matched']); cmd(name+'C',z['clicks'])
    cmd(name+'CTR',f"{z['replay_ctr']*100:.3f}\\%")

for name,key in [('SeedRand','random'),('SeedCtx','contextual_greedy'),('SeedCF','epsilon_greedy')]:
    v=seed[key]
    cmd(name,f"{v['mean']*100:.3f}\\%"); cmd(name+'SD',f"{v['sd']*100:.3f}")

def sim(policy,scenario):
    v=[x['dynamic_regret'] for x in c['simulation'] if x['policy']==policy and x['scenario']==scenario]
    return f'{sum(v)/len(v):.2f}'
for name,policy in [('PostRand','Random'),('PostLin','LinUCB (disjoint)'),('PostWin','Window LinUCB (300)')]:
    for short,scenario in [('S','stationary'),('A','abrupt'),('G','gradual')]:
        cmd(name+short,sim(policy,scenario))

summary=r['simulation']['summary']
for short,scenario in [('S','stationary'),('A','abrupt'),('G','gradual')]:
    o=summary[scenario]['original6']; i=summary[scenario]['intercept7']
    cmd('ExtLin'+short,f"{o['LinUCB (disjoint)']['mean']:.2f}")
    cmd('ExtWin'+short,f"{o['Window-300']['mean']:.2f}")
    cmd('ExtIntLin'+short,f"{i['LinUCB (disjoint)']['mean']:.2f}")
    cmd('ExtIntWin'+short,f"{i['Window-300']['mean']:.2f}")

index={(x['pool'],x['fraction'],x['policy']):x for x in s['results']}
def sp(pool,fraction,policy):
    x=index[pool,fraction,policy]
    return f"{x['replay_ctr']*100:.3f}\\%" if x['matched'] else '---'
fr=[1.0,.1,.05,.01]
def series(pool,policy):
    return '/'.join(sp(pool,f,policy) for f in fr)
sparse=(f'Native pool, 100/10/5/1\\% warmup: Hybrid {series("native","hybrid")} vs '
        f'Disjoint {series("native","disjoint")}. In the enlarged 50-article pool both '
        f'LinUCB policies have zero matches, so their CTR is undefined.')
cmd('SparseSummary',sparse)

(R/'slides_numbers.tex').write_text('% Generated by make_slide_numbers.py.\n'+'\n'.join(lines)+'\n',encoding='utf-8')
print('wrote slides_numbers.tex')
